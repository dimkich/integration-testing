-- noinspection SqlResolveForFile
CREATE TABLE IF NOT EXISTS users (
    id INT PRIMARY KEY,
    name VARCHAR(100),
    email VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS orders (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS messages (
    id INT PRIMARY KEY,
    body TEXT
);

CREATE TABLE IF NOT EXISTS documents (
    id INT PRIMARY KEY,
    status VARCHAR(50),
    content TEXT
);

ALTER TABLE documents ALTER COLUMN content SET STORAGE EXTERNAL;

CREATE TABLE IF NOT EXISTS generated_users (
    id INT PRIMARY KEY,
    name VARCHAR(100),
    name_upper VARCHAR(100) GENERATED ALWAYS AS (upper(name)) STORED
);

CREATE TABLE IF NOT EXISTS identity_users (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS identity_profiles (
    id INT PRIMARY KEY,
    token BIGINT GENERATED ALWAYS AS IDENTITY,
    name TEXT
);

CREATE TABLE IF NOT EXISTS nokey_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS nokey_complex (
    id BIGINT,
    name TEXT,
    data JSONB,
    tags TEXT[],
    payload BYTEA
);

CREATE TABLE IF NOT EXISTS tag_values (
    id INT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS escape_values (
    id INT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS dropped_columns (
    id INT PRIMARY KEY,
    removed TEXT,
    value TEXT
);

ALTER TABLE dropped_columns DROP COLUMN IF EXISTS removed;

CREATE TABLE IF NOT EXISTS spi_values (
    id INT PRIMARY KEY,
    location POINT
);

CREATE TABLE IF NOT EXISTS serde_values (
    id INT PRIMARY KEY,
    data JSONB,
    payload BYTEA
);

CREATE EXTENSION IF NOT EXISTS hstore;

CREATE TABLE IF NOT EXISTS typed_fixture_edges (
    id INT PRIMARY KEY,
    ts_tz TIMESTAMPTZ,
    t_tz TIMETZ,
    jsb JSONB,
    xml_c XML,
    hs HSTORE,
    bits_col BIT(8),
    tags TEXT[]
);

CREATE TABLE IF NOT EXISTS advanced (
    id INT PRIMARY KEY,
    data JSONB,
    tags TEXT[],
    ext_id UUID
);

CREATE TABLE IF NOT EXISTS excluded_values (
    id INT PRIMARY KEY,
    ignored_text TEXT,
    ignored_number INT,
    payload JSONB,
    payload_hstore HSTORE
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'tinyint') THEN
        EXECUTE 'CREATE DOMAIN tinyint AS SMALLINT';
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS datatypes (
    id INT PRIMARY KEY,
    tiny TINYINT,
    ts TIMESTAMP,
    ts_tz TIMESTAMPTZ,
    d DATE,
    t TIME,
    t_tz TIMETZ,
    ivl INTERVAL,
    num NUMERIC(10, 2),
    flag BOOLEAN,
    sm SMALLINT,
    big BIGINT,
    f4 REAL,
    f8 DOUBLE PRECISION,
    bin BYTEA,
    js JSON,
    jsb JSONB,
    hs HSTORE,
    inet_c INET,
    xml_c XML,
    bits_col BIT(8),
    varbit_col VARBIT(5),
    bits_zero_col BIT(8)
);

CREATE TABLE IF NOT EXISTS serde_custom_values (
    id INT PRIMARY KEY,
    tiny TINYINT
);

CREATE TABLE IF NOT EXISTS array_types (
    id INT PRIMARY KEY,
    ts_arr TIMESTAMP[],
    uuid_arr UUID[],
    num_arr NUMERIC(10, 2)[],
    matrix INT[][]
);

ALTER TABLE array_types ADD COLUMN IF NOT EXISTS matrix INT[][];

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'order_status') THEN
        CREATE TYPE order_status AS ENUM ('NEW', 'PROCESSED', 'DONE');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'address') THEN
        CREATE TYPE address AS (city VARCHAR(100), zip VARCHAR(10));
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS exotic (
    id INT PRIMARY KEY,
    status order_status,
    status_arr order_status[],
    addr address,
    rng INT4RANGE,
    drange DATERANGE,
    tsrng TSRANGE,
    tstzrng TSTZRANGE,
    numrng NUMRANGE,
    tsv TSVECTOR,
    hs HSTORE
);

CREATE TABLE IF NOT EXISTS nullable (
    id INT PRIMARY KEY,
    txt TEXT,
    num NUMERIC(10, 2),
    ts TIMESTAMP,
    js JSONB,
    tags TEXT[],
    status order_status
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_user') THEN
        CREATE ROLE app_user LOGIN PASSWORD 'app_pw';
    END IF;
END
$$;

GRANT USAGE ON SCHEMA public TO app_user;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA public TO app_user;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO app_user;
GRANT UPDATE ON ALL SEQUENCES IN SCHEMA public TO app_user;

ALTER SEQUENCE IF EXISTS identity_users_id_seq RESTART WITH 1;
ALTER SEQUENCE IF EXISTS identity_profiles_token_seq RESTART WITH 1;
